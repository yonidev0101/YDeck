// Builds vanish.html from trick.html's shared helpers (fonts, headline, mark, icons, widget, finger, grain)
// plus vanish-scene.js. node make-vanish.cjs
const fs = require('fs'), path = require('path');
const src = fs.readFileSync(path.join(__dirname, 'trick.html'), 'utf8');
const scene = fs.readFileSync(path.join(__dirname, 'vanish-scene.js'), 'utf8');
const head = src.slice(0, src.indexOf('// ---- the account reel ----'));
const grainStart = src.indexOf('// ---- grain ----'), grainEnd = src.indexOf('window.render =');
const tail = src.slice(src.indexOf('// fonts used only inside the canvas'));
let out = head
  // the widget's tap time comes from the scene
  .replace("seg(t, 7.6, 0.22)) : 0;", "seg(t, TAP, 0.22)) : 0;")
  .replace("const ring = seg(t, 7.65, 0.7);", "const ring = seg(t, TAP + 0.05, 0.7);")
  .replace(/<!--[\s\S]*?-->/, '<!-- "Magic #2: the vanishing". GENERATED by make-vanish.cjs from trick.html + vanish-scene.js: edit those. -->')
  + src.slice(grainStart, grainEnd) + scene + '\n' + tail;
out = out.replace(/window\.DURATION = 14\.4;\n(?=\/\/ fonts)/, '');
fs.writeFileSync(path.join(__dirname, 'vanish.html'), out);
console.log('vanish.html', out.length);
