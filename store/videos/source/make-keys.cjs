// Builds keys.html from trick.html's shared helpers (fonts, headline, mark, icons, widget, finger, grain)
// plus keys-scene.js. node make-keys.cjs
const fs = require('fs'), path = require('path');
const src = fs.readFileSync(path.join(__dirname, 'trick.html'), 'utf8');
const scene = fs.readFileSync(path.join(__dirname, 'keys-scene.js'), 'utf8');
const head = src.slice(0, src.indexOf('// ---- the account reel ----'));
const grainStart = src.indexOf('// ---- grain ----'), grainEnd = src.indexOf('window.render =');
const tail = src.slice(src.indexOf('// fonts used only inside the canvas'));
let out = head
  // the widget's tap time comes from the scene
  .replace("seg(t, 7.6, 0.22)) : 0;", "seg(t, TAP, 0.22)) : 0;")
  .replace("const ring = seg(t, 7.65, 0.7);", "const ring = seg(t, TAP + 0.05, 0.7);")
  // the tiles can be hidden while the keys fly in to become them
  .replace(/( {4}if \(a <= 0)\) return;(\r?\n {4}const \[sx, sy\])/, '$1 || NO_TILES) return;$2')
  .replace(/<!--[\s\S]*?-->/, '<!-- "The keys". GENERATED by make-keys.cjs from trick.html + keys-scene.js: edit those. -->')
  + src.slice(grainStart, grainEnd) + scene + '\n' + tail;
out = out.replace(/window\.DURATION = 14\.4;\n(?=\/\/ fonts)/, '');
fs.writeFileSync(path.join(__dirname, 'keys.html'), out);
console.log('keys.html', out.length);
